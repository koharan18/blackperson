test('changing input mode while a file loads cannot restore the old roster',async({page})=>{
  await page.goto('/login');
  await page.getByLabel('아이디').fill('ui@example.invalid');
  await page.getByLabel('비밀번호',{exact:true}).fill('Ui-test-password-123!');
  await page.getByRole('button',{name:'관리 콘솔 접속'}).click();
  await page.getByRole('navigation',{name:'주 메뉴'}).getByRole('link',{name:'명단 확인',exact:true}).click();
  let release,intercepted;
  const waiting=new Promise(r=>{release=r;});
  const started=new Promise(r=>{intercepted=r;});
  await page.route('**/assets/roster-*.js',async route=>{intercepted();await waiting;await route.continue();});
  await page.locator('#roster-file').setInputFiles({name:'old-roster.csv',mimeType:'text/csv',buffer:Buffer.from('이름,전화번호\n이전명단,01012345678')});
  await started;
  await page.getByRole('button',{name:'텍스트로 확인',exact:true}).click();
  release();
  await page.waitForLoadState('networkidle');
  await expect(page.getByRole('cell',{name:'이전명단',exact:true})).toHaveCount(0);
  await expect(page.getByRole('button',{name:'기존 이력과 비교'})).toHaveCount(0);
});

